// Regenerates THIRD_PARTY_LICENSES.md: every Rust crate and production npm package that ships
// inside Tandem, with its declared license. Run: node scripts/third-party.mjs
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const run = (cmd) => execSync(cmd, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

// Rust: only crates actually linked into the Windows release build.
const meta = JSON.parse(
  run("cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-msvc"),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const roots = meta.workspace_members;
const seen = new Set();
const stack = [...roots];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    // Skip build-only and dev-only edges: they do not ship in the binary.
    if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
  }
}
const crates = [...seen]
  .filter((id) => !roots.includes(id))
  .map((id) => byId.get(id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? "see license file" : "unspecified"), repo: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// npm: production dependency tree only (dev tools are not bundled).
const tree = JSON.parse(run("npm ls --omit=dev --all --json --long"));
const pkgs = new Map();
const walk = (deps) => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    // Optional peers that are not installed (no version) do not ship.
    if (!d.version) continue;
    const key = `${name}@${d.version}`;
    if (!pkgs.has(key)) {
      const lic = typeof d.license === "string" ? d.license : d.license?.type ?? "unspecified";
      const repo = typeof d.repository === "string" ? d.repository : d.repository?.url ?? "";
      pkgs.set(key, { name, version: d.version, license: lic, repo: repo.replace(/^git\+/, "") });
    }
    walk(d.dependencies);
  }
};
walk(tree.dependencies);
const npm = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name));

const summary = (list) => {
  const counts = {};
  for (const p of list) counts[p.license] = (counts[p.license] ?? 0) + 1;
  return Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ");
};
const table = (list) =>
  ["| Package | Version | License |", "|---|---|---|", ...list.map((p) => `| ${p.repo ? `[${p.name}](${p.repo})` : p.name} | ${p.version} | ${p.license} |`)].join("\n");

writeFileSync(
  "THIRD_PARTY_LICENSES.md",
  `# Third-party licenses

Tandem is licensed under the GNU AGPL-3.0-or-later (see LICENSE and NOTICE). It links or
bundles the open-source components below, each under its own license. All are permissive
licenses compatible with the AGPL. Their full texts are in each package's source distribution.

Generated by \`node scripts/third-party.mjs\`. Do not edit by hand.

## Rust crates (${crates.length})

${summary(crates)}

${table(crates)}

## JavaScript packages (${npm.length})

${summary(npm)}

${table(npm)}
`,
);
console.log(`crates: ${crates.length} (${summary(crates)})\nnpm: ${npm.length} (${summary(npm)})`);
